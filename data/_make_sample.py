def write_norms() -> int:
    rows = 0
    with open(HERE / "norms.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["gender", "age_band", "item", "percentile", "value"])
        for gender in ("M", "F"):
            for band in AGE_BANDS:
                for item in ITEM_ORDER:
                    for i, p in enumerate(PERCENTILES):
                        w.writerow([gender, band, item, p, norm_value(gender, band, item, i)])
                        rows += 1
    return rows


def write_courses() -> int:
    with open(HERE / "courses.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow([
            "course_id", "title", "facility", "lat", "lng", "weekday", "start_time",
            "sport", "tag_strength", "tag_endurance", "tag_flex", "tag_cardio", "tag_power",
        ])
        for course in COURSES:
            sport = course[7]
            tags = SPORT_TAGS.get(sport)
            if tags is None:
                raise SystemExit(f"SPORT_TAGS에 '{sport}' 태그가 없습니다")
            w.writerow(list(course) + list(tags))
    return len(COURSES)


