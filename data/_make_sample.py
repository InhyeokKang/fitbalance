def write_norms() -> int:
    rows = 0
    with open(HERE / "norms.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["gender", "age_band", "item", "percentile", "value"])
        for (gender, band), items in NORMS.items():
            for item in ITEM_ORDER:
                for p, v in zip(PERCENTILES, items[item]):
                    w.writerow([gender, band, item, p, v])
                    rows += 1
    return rows


def write_courses() -> int:
    with open(HERE / "courses.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow([
            "course_id", "title", "facility", "lat", "lng", "weekday", "start_time",
            "sport", "tag_strength", "tag_flex", "tag_cardio", "tag_balance",
        ])
        w.writerows(COURSES)
    return len(COURSES)


